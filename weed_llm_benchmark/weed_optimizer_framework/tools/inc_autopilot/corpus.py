# A quote shorter than this proves nothing about the line it names ("the",
# "0.3"); the validator refuses it rather than counting it as a resolved quote.
# Only the passage's own text counts: the "KIND [topic]: " label and the
# truncation mark are the corpus's, not the note's.
MIN_QUOTE_CHARS = 20

# The committed source of the corpus, relative to the corpus directory.
SOURCE_FILE = "_source/notes.md"
SOURCE_MARK = ("<!-- extract of the curated literature notes: every TOPIC, paper and "
               "RESULT/US/CORRECTION line inc_autopilot/corpus.py build reads, verbatim; "
               "written by corpus.py build, do not hand-edit -->")

# BM25 parameters: the textbook defaults. The corpus is a few hundred short
# lines, far too small to tune anything on.
BM25_K1 = 1.5
BM25_B = 0.75

_STOP = frozenset("""a an and are as at be by for from has have in is it its of on or
that the this to was were with which what when where who than then these those
their there they we our you your not no can will would should could may might
into over under about after before also only more most such both each other""".split())

_TOKEN_RE = re.compile(r"[a-z0-9]+(?:[.\-][a-z0-9]+)*")
_TOPIC_RE = re.compile(r"^=+ TOPIC (\S+) =+$")
_ENTRY_RE = re.compile(r"^- \[([^\]]+)\] (.+)$")
_FIELD_RE = re.compile(r"^    (RESULT|US|CORRECTION): (.*)$")
_ARXIV_URL_RE = re.compile(r"(?:arxiv\.org/(?:abs|html|pdf)/|ar5iv\.labs\.arxiv\.org/html/)"
                           r"(\d{4}\.\d{4,5})")
_ARXIV_TXT_RE = re.compile(r"arXiv[: ](\d{4}\.\d{4,5})")


# --- where the corpus lives ---------------------------------------------------

def default_dir():
    """docs/literature of the checkout this module sits in.

    INC_LITERATURE_DIR overrides. Otherwise the nearest ancestor holding
    docs/literature/index.json: the git root on the lab, and the nested
    (git-tracked) copy's root on the cluster, where the brain job runs from.
    """
    env = os.environ.get("INC_LITERATURE_DIR")
    if env:
        return Path(env)
    here = Path(__file__).resolve()
    for parent in here.parents:
        cand = parent / "docs" / "literature"
        if (cand / "index.json").is_file():
            return cand
    return here.parents[4] / "docs" / "literature"


# --- building the corpus from the curated notes -------------------------------

def _split_header(rest):
    """'<title> (<venue>, <year>) <url>' -> (title, venue, year, url)."""
    rest = rest.strip()
    url = ""
    head, _, last = rest.rpartition(" ")
    if last.startswith("http"):
        url, rest = last, head.strip()
    title, venue, year = rest, "", ""
    if rest.endswith(")"):
        depth = 0
        for i in range(len(rest) - 1, -1, -1):
            if rest[i] == ")":
                depth += 1
            elif rest[i] == "(":
                depth -= 1
                if depth == 0:
                    inner = rest[i + 1:-1]
                    title = rest[:i].strip()
                    v, sep, y = inner.rpartition(", ")
                    if sep and re.fullmatch(r"\d{4}", y.strip()):
                        venue, year = v.strip(), y.strip()
                    else:
                        venue = inner.strip()
                    break
    return title, venue, year, url


def _slug(title):
    words = [w for w in re.findall(r"[a-z0-9]+", title.lower()) if w not in _STOP]
    return "-".join(words[:6]) or "paper"


def paper_id(title, venue, url):
    m = _ARXIV_URL_RE.search(url or "") or _ARXIV_TXT_RE.search(venue or "")
    return m.group(1) if m else _slug(title)


def _field_text(text):
    text = " ".join(str(text).split())
    # The notes were collected with each field capped near 400 characters; a
    # field that stops there mid-sentence is marked so no reader takes the cut
    # for the note's end.
    if len(text) >= 380 and not text.endswith((".", "!", "?", ")", "\"", "'")):
        text = text + " " + TRUNCATED_MARK
    return text


def parse_notes(text):
    """The curated notes -> [{topic, status, title, venue, year, url, id, fields}]."""
    entries, topic, cur = [], None, None
    for raw in text.splitlines():
        line = raw.rstrip("\n")
        m = _TOPIC_RE.match(line.strip())
        if m:
            topic, cur = m.group(1), None
            continue
        m = _ENTRY_RE.match(line)
        if m and topic:
            title, venue, year, url = _split_header(m.group(2))
            cur = {"topic": topic, "status": m.group(1), "title": title, "venue": venue,
                   "year": year, "url": url, "id": paper_id(title, venue, url), "fields": []}
            entries.append(cur)
            continue
        m = _FIELD_RE.match(line)
        if m and cur is not None:
            cur["fields"].append((m.group(1), _field_text(m.group(2))))
            continue
        cur = None      # SYNTHESIS / GAPS / VERIFIER blocks are not paper notes
    return entries


def source_extract(text):
    """The lines of the curated notes the build reads, verbatim.

    TOPIC headers, paper entries and the RESULT/US/CORRECTION fields parse_notes
    attaches to an entry. Every other line (the sweeps' SYNTHESIS, GAPS and
    VERIFIER blocks, which are not paper notes) is left out, and so is a field
    line parse_notes would not attach, so parse_notes reads the same entries
    from the extract as from the full notes (build() checks this).
    """
    out, topic, cur = [SOURCE_MARK], None, False
    for raw in text.splitlines():
        line = raw.rstrip("\n")
        m = _TOPIC_RE.match(line.strip())
        if m:
            topic, cur = m.group(1), False
            out.append(line.strip())
            continue
        if topic and _ENTRY_RE.match(line):
            cur = True
            out.append(line)
            continue
        if cur and _FIELD_RE.match(line):
            out.append(line)
            continue
        cur = False
    return "\n".join(out) + "\n"


def _levers_for(topics):
    out = []
    for t in topics:
        for lv in TOPIC_LEVERS.get(t, []):
            if lv not in out:
                out.append(lv)
    return out


def _render(pid, group):
    first = group[0]
    topics = []
    for e in group:
        if e["topic"] not in topics:
            topics.append(e["topic"])
    venues = []
    for e in group:
        v = ", ".join(x for x in (e["venue"], e["year"]) if x)
        if v and v not in venues:
            venues.append(v)
    levers = _levers_for(topics)
    lines = ["# %s" % first["title"],
             GENERATED_MARK,
             "id: %s" % pid,
             "bib: %s. %s. %s" % (first["title"], "; ".join(venues) or "venue not recorded",
                                  first["url"] or "no url recorded"),
             "topics: %s" % ", ".join(topics),
             "status: %s" % ", ".join("%s=%s" % (e["topic"], e["status"]) for e in group),
             "informs: %s" % (", ".join(levers) or "none"),
             "provenance: %s" % PROVENANCE,
             "",
             "## Passages"]
    passages, seen = [], set()
    for e in group:
        for kind, text in e["fields"]:
            key = (kind, text)
            if key in seen:
                continue
            seen.add(key)
            lines.append("%s [%s]: %s" % (kind, e["topic"], text))
            passages.append({"line": len(lines), "kind": kind, "topic": e["topic"]})
    return lines, {"id": pid, "file": "%s.md" % pid, "title": first["title"],
                   "url": first["url"], "venues": venues, "year": first["year"],
                   "topics": topics, "levers": levers,
                   "status": {e["topic"]: e["status"] for e in group},
                   "n_lines": len(lines), "n_passages": len(passages),
                   "passages": passages}


def build(notes_path, out_dir=None, aliases=None):
    """Write <id>.md per paper, _source/notes.md and index.json. Returns the index dict.

    `notes_path` is the collected notes or the committed extract
    (_source/notes.md); both give the same files. `aliases` defaults to
    ALIASES; every alias target must be a paper of the notes, so a renamed or
    dropped seed paper fails the build.

    Deterministic: the same notes give byte-identical files. Files of papers no
    longer in the notes are removed, so the index and the directory agree.
    """
    notes_path = Path(notes_path)
    text = notes_path.read_bytes().decode("utf-8")
    extract = source_extract(text)
    entries = parse_notes(extract)
    if not entries:
        raise ValueError("no paper entries found in %s" % notes_path)
    if parse_notes(text) != entries:
        raise ValueError("the source extract of %s does not parse to the same entries" % notes_path)
    groups, order = {}, []
    for e in entries:
        if not e["fields"]:
            raise ValueError("entry %r (%s) has no RESULT/US/CORRECTION line"
                             % (e["title"], e["topic"]))
        if e["id"] not in groups:
            groups[e["id"]] = []
            order.append(e["id"])
        groups[e["id"]].append(e)
    aliases = ALIASES if aliases is None else dict(aliases)
    missing = sorted(a for a, t in aliases.items() if t is not None and t not in groups)
    if missing:
        raise ValueError("alias target(s) not in the notes: %s" % ", ".join(missing))
    out = Path(out_dir) if out_dir else default_dir()
    out.mkdir(parents=True, exist_ok=True)
    src = out / SOURCE_FILE
    src.parent.mkdir(parents=True, exist_ok=True)
    extract_bytes = extract.encode("utf-8")
    src.write_bytes(extract_bytes)
    papers = []
    for pid in sorted(order):
        lines, meta = _render(pid, groups[pid])
        (out / meta["file"]).write_text("\n".join(lines) + "\n", encoding="utf-8")
        papers.append(meta)
    keep = {p["file"] for p in papers} | {"index.json", "README.md"}
    for f in out.glob("*.md"):
        if f.name not in keep and f.read_text(encoding="utf-8").splitlines()[1:2] == [GENERATED_MARK]:
            f.unlink()
    topics = {}
    for e in entries:
        topics[e["topic"]] = topics.get(e["topic"], 0) + 1
    index = {"schema": SCHEMA,
             "provenance": PROVENANCE,
             "source_notes": {"path": SOURCE_FILE,
                              "sha256": hashlib.sha256(extract_bytes).hexdigest(),
                              "entries": len(entries), "per_topic": topics},
             "topic_levers": TOPIC_LEVERS,
             "aliases": {k: v for k, v in sorted(aliases.items())},
             "min_quote_chars": MIN_QUOTE_CHARS,
             "n_papers": len(papers),
             "n_passages": sum(p["n_passages"] for p in papers),
             "papers": papers}
    (out / "index.json").write_text(json.dumps(index, indent=1, sort_keys=True) + "\n",
                                    encoding="utf-8")
    return index


# --- reading it back ------------------------------------------------------------

def tokens(text):
    return [t for t in _TOKEN_RE.findall(str(text).lower()) if t not in _STOP and len(t) > 1]


class Corpus(object):
    """The committed corpus: exact line lookup plus BM25 over passage lines."""

    def __init__(self, root=None):
        self.root = Path(root) if root else default_dir()
        index_path = self.root / "index.json"
        if not index_path.is_file():
            raise FileNotFoundError("no literature index at %s" % index_path)
        self.index = json.loads(index_path.read_text(encoding="utf-8"))
        self.papers = {p["id"]: p for p in self.index.get("papers", [])}
        self._lines = {}
        self.docs = []          # [(paper_id, line, kind, topic, text, token list)]
        for pid in sorted(self.papers):
            meta = self.papers[pid]
            lines = (self.root / meta["file"]).read_text(encoding="utf-8").splitlines()
            self._lines[pid] = lines
            title_toks = tokens(meta.get("title", ""))
            for p in meta.get("passages", []):
                text = lines[p["line"] - 1] if 0 < p["line"] <= len(lines) else ""
                m = PASSAGE_RE.match(text)
                if not m:
                    raise ValueError("%s line %d is indexed as a passage but is not one"
                                     % (meta["file"], p["line"]))
                # The title's words are indexed with each passage so a passage
                # is found by what the paper is about, not only by its own words.
                self.docs.append((pid, p["line"], p["kind"], p["topic"], text,
                                  tokens(m.group(3)) + title_toks))
        self._df = {}
        for d in self.docs:
            for t in set(d[5]):
                self._df[t] = self._df.get(t, 0) + 1
        self._avgdl = (sum(len(d[5]) for d in self.docs) / float(len(self.docs))) if self.docs else 1.0

    def canonical_id(self, paper_id):
        """The corpus id for an id or a known alias (ALIASES), or None."""
        pid = str(paper_id)
        if pid in self.papers:
            return pid
        target = (self.index.get("aliases") or {}).get(pid)
        return target if target in self.papers else None

    def line(self, paper_id, line):
        """The text of `line` (1-based) of paper `paper_id` (or its alias), or None."""
        lines = self._lines.get(self.canonical_id(paper_id) or "")
        if lines is None or isinstance(line, bool) or not isinstance(line, int):
            return None
        if not 0 < line <= len(lines):
            return None
        return lines[line - 1]

    def is_passage(self, paper_id, line):
        meta = self.papers.get(self.canonical_id(paper_id) or "")
        return bool(meta) and any(p["line"] == line for p in meta.get("passages", []))

    def passage(self, paper_id, line):
        """{"kind", "topic"} of a passage line, or None (a header line, or no such line)."""
        meta = self.papers.get(self.canonical_id(paper_id) or "")
        for p in (meta or {}).get("passages", []):
            if p["line"] == line:
                return {"kind": p["kind"], "topic": p["topic"]}
        return None

    def check_quote(self, paper_id, line, quote):
        """(ok, reason). The quote must be a verbatim substring of a passage line
        that carries at least MIN_QUOTE_CHARS characters of the passage's own
        text: the "KIND [topic]: " label and the truncation mark do not count."""
        if self.canonical_id(paper_id) is None:
            return False, "paper %r is not in the corpus" % (paper_id,)
        text = self.line(paper_id, line)
        if text is None:
            return False, "paper %r has no line %r" % (paper_id, line)
        if not self.is_passage(paper_id, line):
            return False, "line %r of %r is not a passage line (header lines are not citable)" % (
                line, paper_id)
        if not isinstance(quote, str) or len(quote.strip()) < MIN_QUOTE_CHARS:
            return False, "quote is shorter than %d characters" % MIN_QUOTE_CHARS
        if quote not in text:
            return False, "quote is not a verbatim substring of %s line %d" % (paper_id, line)
        m = PASSAGE_RE.match(text)
        start, end = m.start(3), m.end(3)
        if text.endswith(TRUNCATED_MARK):
            end = len(text.rstrip()) - len(TRUNCATED_MARK)
        best, at = 0, text.find(quote)
        while at >= 0:
            lo, hi = max(at, start), min(at + len(quote), end)
            if hi > lo:
                best = max(best, len(text[lo:hi].strip()))
            at = text.find(quote, at + 1)
        if best < MIN_QUOTE_CHARS:
            return False, ("quote carries %d characters of the passage's own text, fewer than %d "
                           "(the KIND [topic]: label and the truncation mark do not count)"
                           % (best, MIN_QUOTE_CHARS))
        return True, ""

    def search(self, query, k=8, levers=None):
        """Top-k passages by BM25: [{paper_id, line, kind, topic, text, score, title, levers}].

        With `levers`, passages of papers that inform any of them rank first;
        the rest fill the list if fewer than k of those match at all. Ties are
        broken by (paper id, line), so the result is deterministic.
        """
        q = tokens(query)
        if not q or not self.docs:
            return []
        n = float(len(self.docs))
        scored = []
        for d in self.docs:
            tf = {}
            for t in d[5]:
                tf[t] = tf.get(t, 0) + 1
            s = 0.0
            dl = float(len(d[5]))
            for t in set(q):
                f = tf.get(t, 0)
                if not f:
                    continue
                df = self._df.get(t, 0)
                idf = math.log(1.0 + (n - df + 0.5) / (df + 0.5))
                s += idf * f * (BM25_K1 + 1) / (f + BM25_K1 * (1 - BM25_B + BM25_B * dl / self._avgdl))
            if s > 0:
                scored.append((s, d))
        scored.sort(key=lambda x: (-x[0], x[1][0], x[1][1]))
        want = set(levers or [])
        if want:
            first = [x for x in scored if want & set(self.papers[x[1][0]].get("levers", []))]
            rest = [x for x in scored if x not in first]
            scored = first + rest
        out = []
        for s, d in scored[:k]:
            meta = self.papers[d[0]]
            out.append({"paper_id": d[0], "line": d[1], "kind": d[2], "topic": d[3],
                        "text": d[4], "score": round(s, 4), "title": meta.get("title"),
                        "levers": meta.get("levers", [])})
        return out


def check_corpus(root=None):
    """[problems]: every indexed passage parses, every file is indexed, counts
    agree, the committed source extract matches its recorded sha256, and a
    rebuild from it gives byte-identical files."""
    problems = []
    try:
        c = Corpus(root)
    except Exception as exc:
        return ["corpus unreadable: %s" % exc]
    files = {p.name for p in c.root.glob("*.md")} - {"README.md"}
    indexed = {m["file"] for m in c.papers.values()}
    for f in sorted(files - indexed):
        problems.append("%s is not in index.json" % f)
    for f in sorted(indexed - files):
        problems.append("index.json names %s, which does not exist" % f)
    for pid, meta in c.papers.items():
        if len(c._lines[pid]) != meta.get("n_lines"):
            problems.append("%s has %d lines, index says %s" % (meta["file"], len(c._lines[pid]),
                                                                meta.get("n_lines")))
        if c._lines[pid][1:2] != [GENERATED_MARK]:
            problems.append("%s lacks the generated-file mark" % meta["file"])
    if c.index.get("n_passages") != len(c.docs):
        problems.append("index counts %s passages, files hold %d" % (c.index.get("n_passages"),
                                                                    len(c.docs)))
    if c.index.get("aliases") != {k: v for k, v in sorted(ALIASES.items())}:
        problems.append("index.json aliases differ from corpus.ALIASES: rebuild the corpus")
    problems.extend(check_source(c.root, c.index))
    return problems


def _corpus_files(root):
    root = Path(root)
    out = {}
    for f in sorted(root.rglob("*")):
        rel = f.relative_to(root).as_posix()
        if f.is_file() and rel != "README.md" and (rel.endswith(".md") or rel == "index.json"):
            out[rel] = f.read_bytes()
    return out


def check_source(root, index=None):
    """[problems]: the committed source extract exists, matches the sha256
    index.json records, and rebuilds the corpus byte for byte (with the
    aliases the index records, and this module's topic-to-lever map)."""
    root = Path(root)
    if index is None:
        index = json.loads((root / "index.json").read_text(encoding="utf-8"))
    rec = index.get("source_notes") or {}
    rel = rec.get("path")
    if not rel:
        return ["index.json records no source_notes.path: the corpus cannot be rebuilt "
                "from the repository"]
    src = root / rel
    if not src.is_file():
        return ["the source notes %s named by index.json do not exist" % rel]
    got = hashlib.sha256(src.read_bytes()).hexdigest()
    if got != rec.get("sha256"):
        return ["%s has sha256 %s, index.json records %s" % (rel, got[:12],
                                                            str(rec.get("sha256"))[:12])]
    tmp = Path(tempfile.mkdtemp(prefix="inc_lit_check_"))
    try:
        try:
            build(src, tmp, aliases=index.get("aliases") or {})
        except Exception as exc:
            return ["a rebuild from %s fails: %s" % (rel, exc)]
        want, have = _corpus_files(root), _corpus_files(tmp)
        diff = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if diff:
            return ["a rebuild from %s differs from the committed corpus in %d file(s): %s"
                    % (rel, len(diff), ", ".join(diff[:5]))]
    finally:
        shutil.rmtree(str(tmp), ignore_errors=True)
    return []


def _main(argv=None):
    ap = argparse.ArgumentParser(prog="inc_autopilot.corpus", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd")
    b = sub.add_parser("build", help="write docs/literature from the curated notes")
    b.add_argument("--notes", required=True)
    b.add_argument("--out", default=None)
    s = sub.add_parser("search", help="BM25 over the passage lines")
    s.add_argument("query")
    s.add_argument("--k", type=int, default=8)
    s.add_argument("--lever", action="append", default=[])
    sub.add_parser("check", help="consistency of files and index")
    args = ap.parse_args(argv)
    if args.cmd == "build":
        idx = build(args.notes, args.out)
        print("built %d papers, %d passages from %d note entries"
              % (idx["n_papers"], idx["n_passages"], idx["source_notes"]["entries"]))
        return 0
    if args.cmd == "search":
        for hit in Corpus().search(args.query, k=args.k, levers=args.lever):
            print("%-28s line %-3d %.3f  %s" % (hit["paper_id"], hit["line"], hit["score"],
                                                hit["text"][:110]))
        return 0
    if args.cmd == "check":
        problems = check_corpus()
        for p in problems:
            print("PROBLEM", p)
        print("%d problem(s)" % len(problems))
        return 1 if problems else 0
    ap.print_help()
    return 2


