"""The line-addressed literature corpus the INC research brain may quote.

docs/INC_AUTOPILOT.md (c): the brain's proposals may cite literature, and
`validate.py` accepts a literature quote only when it is a verbatim substring
of the corpus line it names. This module owns both sides of that: it builds
`docs/literature/<id>.md` + `docs/literature/index.json` from the curated
literature notes, and it reads them back (plain BM25 over the passage lines,
and the exact line lookup the validator uses).

What the corpus is, honestly. The passages are NOT verbatim text from the
papers. They are curated research notes, one RESULT, US and CORRECTION line
per paper per topic sweep, each checked against the paper by a verifier (the
CORRECTION line records what was checked and what was corrected). The contract
asked for verbatim passages from the PDFs; nothing in this repo holds those,
and a model's paraphrase of a PDF would be worse than a checked note. So a
"literature quote" in a brain plan is a quote of these notes, which every
corpus file and docs/literature/README.md state in their header. Some note
fields were cut at about 400 characters when the notes were collected; such a
line ends with TRUNCATED_MARK.

The source is committed with the corpus: `build` writes `_source/notes.md`,
the extract of the curated notes it read (every TOPIC, paper and
RESULT/US/CORRECTION line, verbatim; the sweeps' SYNTHESIS, GAPS and VERIFIER
blocks are not paper notes and are left out), and index.json records its
sha256. `check` verifies that hash and that a rebuild from the extract gives
byte-identical files, so the committed corpus stays reproducible from the
repository alone.

File layout (one paper per file; line numbers are the addresses):

    # <title>
    <!-- generated by inc_autopilot/corpus.py build; do not hand-edit -->
    id: <paper id>
    bib: <title>. <venue>, <year>. <url>
    topics: <topic>, ...
    status: <topic>=<verifier|relevance|recommendation>, ...
    informs: L1, X1, ...           (or "none")
    provenance: <the not-verbatim statement>

    ## Passages
    RESULT [<topic>]: ...           <- passage lines: the only citable lines
    US [<topic>]: ...
    CORRECTION [<topic>]: ...

A paper that appears in several topic sweeps (OWL-ST, DINOv2, ...) gets one
file with every sweep's lines, each tagged with its topic.

Levers a paper informs are assigned by topic (TOPIC_LEVERS), not per paper by
hand: continual/replay -> L1 (and the real-loop recipe choice L2, and the LR
re-warm X1), curation/relevance -> L3 (and the leaf-disease X2), label noise
-> L4 (and audit-feeds-attribution X3), attribution and statistics -> L5/D8
(and X3/X4), self-training -> L4, weed-domain papers -> L3, agent papers ->
D13/D14 (prediction tracking, evaluation integrity), web research -> none.

CLI:
    python -m weed_optimizer_framework.tools.inc_autopilot.corpus build --notes NOTES.md [--out DIR]
        (NOTES.md: the collected notes, or the committed ../docs/literature/_source/notes.md)
    python -m weed_optimizer_framework.tools.inc_autopilot.corpus search "replay forgetting" [--k 8] [--lever L1]
    python -m weed_optimizer_framework.tools.inc_autopilot.corpus check
"""
