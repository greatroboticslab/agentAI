"""
train_yolo_on_verified.py — v3.0.74 (2026-06-01) PLACEHOLDER

Stage-5 trigger of the round workflow. The user clicks "Send to training"
when they're satisfied with the human-verified ✓ set for a round. This
script:

  1. Reads registry → finds slugs in target round that are user-verified
  2. Builds a training manifest (YAML for YOLO11) at
     results/framework/train_manifests/round-{N}.yaml
  3. Marks rounds[N].trained = True + ts
  4. Submits a SLURM SBATCH placeholder for the trainer agent
     (run_v3_0_74_yolo_trainer_placeholder.sh)

PLACEHOLDER NOTE: the trainer SBATCH itself is a stub that just touches
a file and exits. Real YOLO11 + RF-DETR training (with backbone choice,
hyperparameters, eval against cwd12 holdout) is Agent 2's domain and
will be wired in a future iteration. This placeholder lets the user see
the button works end-to-end (registry updated, SBATCH queued).

CLI:
    python -m weed_optimizer_framework.tools.train_yolo_on_verified \\
        --round 1 [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(os.environ.get(
    "REPO_ROOT",
    "/ocean/projects/cis240145p/byler/harry/weed_llm_benchmark",
))
REGISTRY = REPO / "results" / "framework" / "dataset_registry.json"
MANIFEST_DIR = REPO / "results" / "framework" / "train_manifests"
SLUG_VERDICTS = REPO / "results" / "framework" / "slug_verdicts.jsonl"
EXEMPLAR_VERDICTS = REPO / "results" / "framework" / "exemplar_verdicts.jsonl"


def _verified_slugs(round_n: int) -> tuple[set, dict]:
    """Return (verified_set, full_registry)."""
    reg = json.load(open(REGISTRY))
    r_slugs = [s for s, info in reg.get("datasets", {}).items()
               if info.get("status") == "downloaded"
               and int(info.get("harvest_round", 0) or 0) == round_n]
    sv = {}
    if SLUG_VERDICTS.exists():
        for line in SLUG_VERDICTS.read_text().splitlines():
            if not line.strip():
                continue
            try:
                e = json.loads(line)
                sv[e.get("slug")] = e.get("verdict")
            except Exception:
                continue
    verified = {s for s in r_slugs if sv.get(s) == "keep"}
    # Class-level verdicts add positive signal
    if EXEMPLAR_VERDICTS.exists():
        for line in EXEMPLAR_VERDICTS.read_text().splitlines():
            if not line.strip():
                continue
            try:
                e = json.loads(line)
                if e.get("verdict") == "exemplar":
                    sl = e.get("slug") or e.get("source_slug")
                    if sl in r_slugs:
                        verified.add(sl)
            except Exception:
                continue
    # Always include cwd12 baselines (frozen ground-truth)
    for baseline in ("cottonweed_holdout", "cottonweed_sp8"):
        if baseline in reg.get("datasets", {}):
            verified.add(baseline)
    return verified, reg


def run(round_n: int, dry_run: bool = False) -> dict:
    verified, reg = _verified_slugs(round_n)
    if not verified:
        return {"ok": False,
                "error": f"Round {round_n} has no verified slugs. "
                         f"Click ✓ keep on at least 1 slug first."}

    # Build YOLO11-style data manifest
    MANIFEST_DIR.mkdir(parents=True, exist_ok=True)
    manifest_path = MANIFEST_DIR / f"round-{round_n}.yaml"

    yaml_lines = [
        f"# Auto-generated by train_yolo_on_verified — round {round_n}",
        f"# {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"# Human-verified slugs: {sorted(verified)}",
        "",
        "names:",  # placeholder — real should derive from class_names
    ]
    # CWD12 12-class default
    cwd12 = ["Carpetweeds", "Crabgrass", "Eclipta", "Goosegrass",
             "Morningglory", "Nutsedge", "PalmerAmaranth", "PricklySida",
             "Purslane", "Ragweed", "Sicklepod", "SpottedSpurge"]
    for i, n in enumerate(cwd12):
        yaml_lines.append(f"  {i}: {n}")
    yaml_lines.extend(["", "train:"])
    for slug in sorted(verified):
        info = reg["datasets"].get(slug, {})
        lp = info.get("local_path", "")
        if lp:
            # Most YOLO datasets store images under <lp>/train/images or <lp>/images
            for cand in ("train/images", "images"):
                if (Path(lp) / cand).is_dir():
                    yaml_lines.append(f"  - {lp}/{cand}")
                    break
    yaml_lines.extend(["", "val:", "  - results/leave4out/dataset_holdout/test/images",
                       "", "test:", "  - results/leave4out/dataset_holdout/test/images"])
    manifest_text = "\n".join(yaml_lines) + "\n"

    result = {
        "ok": True,
        "round": round_n,
        "verified_slugs": sorted(verified),
        "manifest_path": str(manifest_path),
        "manifest_preview": manifest_text[:500],
        "ts": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "dry_run": dry_run,
        "is_placeholder": True,
        "note": ("PLACEHOLDER: training SBATCH script is a stub. Real Agent 2 "
                 "(trainer) wiring is future work."),
    }

    if dry_run:
        print(json.dumps(result, indent=2))
        return result

    # Write manifest
    manifest_path.write_text(manifest_text)

    # Update registry: mark round trained-in-flight
    rmeta = reg.setdefault("rounds", {}).setdefault(str(round_n), {})
    rmeta["trained_at"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    rmeta["train_manifest"] = str(manifest_path)
    # Atomic + locked (unique temp file) — no shared fixed `.tmp` to corrupt.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from registry_lock import atomic_write_json, registry_lock
    with registry_lock(REGISTRY):
        atomic_write_json(REGISTRY, reg)

    # Queue placeholder SBATCH
    placeholder_sh = REPO / "run_v3_0_74_yolo_trainer_placeholder.sh"
    if placeholder_sh.is_file():
        try:
            r = subprocess.run(
                ["sbatch", "--export=ALL,TRAIN_MANIFEST=" + str(manifest_path),
                 str(placeholder_sh)],
                capture_output=True, text=True, timeout=15,
            )
            result["sbatch_stdout"] = r.stdout.strip()
            result["sbatch_stderr"] = r.stderr.strip()
            result["sbatch_ok"] = r.returncode == 0
        except Exception as e:
            result["sbatch_error"] = f"{type(e).__name__}: {e}"
    else:
        result["sbatch_skipped"] = f"placeholder script not at {placeholder_sh}"

    print(json.dumps(result, default=str, indent=2))
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    run(args.round, args.dry_run)


if __name__ == "__main__":
    main()
